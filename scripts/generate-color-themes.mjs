// Build flat light/dark palettes for Web and native clients.
import fs from 'node:fs';
const source = JSON.parse(fs.readFileSync('src/data/color-palettes.json', 'utf8'));
const upstream = JSON.parse(fs.readFileSync('src/data/readme-themes.json', 'utf8'));
const rgb = value => {
 if (!/^[\da-f]{6}$/i.test(value)) throw Error('Invalid palette color: '+value);
 return [0,2,4].map(i=>parseInt(value.slice(i,i+2),16));
};
const hex = c => '#'+c.map(v=>Math.round(v).toString(16).padStart(2,'0')).join('');
const mix=(a,b,t)=>a.map((v,i)=>v*(1-t)+b[i]*t);
const luminance=c=>c.map(x=>{const v=x/255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4;}).reduce((s,v,i)=>s+v*[.2126,.7152,.0722][i],0);
const contrast=(a,b)=>(Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05);
const readable=(color,bg)=>{
 const end=contrast([0,0,0],bg)>contrast([255,255,255],bg)?[0,0,0]:[255,255,255];
 for(let i=0;i<=100;i++){const c=mix(color,end,i/100);if(contrast(c,bg)>=4.6)return c;}
 return end;
};
// Keep the source background in its matching appearance. Derive the other
// appearance from the same hue; transparency and gradients become solid colors.
const sourceColor=value=>{
 let color=value.includes(',')?value.split(',')[1]:value;
 if(color.length===3) color=color.split('').map(c=>c+c).join('');
 return rgb(color.slice(0,6));
};
for(const [upstreamName,p] of Object.entries(upstream)) {
 const name=Object.hasOwn(source,upstreamName)?'readme-'+upstreamName:upstreamName;
 const bg=sourceColor(p.bg_color), accent=sourceColor(p.title_color);
 const dark=luminance(bg)<.179;
 source[name]={label:upstreamName};
 for(const scheme of ['light','dark']) {
  const matching=(scheme==='dark')===dark;
  source[name][scheme]={
   bg:hex(matching?bg:scheme==='light'?mix([255,255,255],bg,.06):mix([18,18,18],accent,.08)).slice(1),
   text:hex(sourceColor(p.text_color)).slice(1),
   accent:hex(accent).slice(1)
  };
 }
}
const palettes={};
for(const [name,p] of Object.entries(source)) {
 palettes[name]={};
 for(const scheme of ['light','dark']) {
  const colors=p[scheme];
  const bg=rgb(colors.bg), text=readable(rgb(colors.text),bg), accent=readable(rgb(colors.accent),bg);
  const on=contrast([0,0,0],accent)>contrast([255,255,255],accent)?[0,0,0]:[255,255,255];
  palettes[name][scheme]={scheme,bg:hex(bg),surface:hex(bg),
   'surface-2':hex(mix(bg,text,.07)), 'input-surface':hex(bg), text:hex(text), muted:hex(readable(mix(bg,text,.8),bg)),
   border:hex(mix(bg,text,.28)),accent:hex(accent),'accent-hover':hex(mix(accent,on,.08)), 'on-accent':hex(on),selection:hex(mix(bg,text,.13)),
   warn:hex(readable(rgb('d29922'),bg))};
 }
}
const banner='Generated by scripts/generate-color-themes.mjs. Includes adapted GitHub Readme Stats themes.\n'
 +'Source: https://github.com/anuraghazra/github-readme-stats/blob/master/themes/index.js\n'
 +fs.readFileSync('docs/licenses/github-readme-stats.txt','utf8').trim();
const labels=Object.fromEntries(Object.entries(source).map(([name,p])=>[name,p.label]));
fs.writeFileSync('src/js/color-themes.js','// '+banner.replaceAll('\n','\n// ').replaceAll('\n// \n','\n//\n')+'\nexport const COLOR_THEMES = '+JSON.stringify(palettes,null,2)+';\nexport const COLOR_THEME_LABELS = '+JSON.stringify(labels,null,2)+';\n');
fs.writeFileSync('src/css/color-themes.css','/* '+banner+' */\n'+Object.entries(palettes).flatMap(([name,variants])=>Object.entries(variants).map(([scheme,p])=>'html[data-color-theme="'+name+'"][data-theme="'+scheme+'"] {\n'+Object.entries(p).map(([k,v])=>k==='scheme'?'  color-scheme: '+v+';':'  --'+k+': '+v+';').join('\n')+'\n}')).join('\n'));
fs.writeFileSync('ios/App/App/NativeColorThemes.swift','// '+banner.replaceAll('\n','\n// ').replaceAll('\n// \n','\n//\n')+'\nimport Foundation\n\nenum AppColorThemes {\n    static let palettes: [String: [String: [String: String]]] = [\n'+Object.entries(palettes).map(([name,variants])=>'        '+JSON.stringify(name)+': [\n'+Object.entries(variants).map(([scheme,p])=>'            '+JSON.stringify(scheme)+': ['+Object.entries(p).map(([k,v])=>JSON.stringify(k)+': '+JSON.stringify(v)).join(', ')+']').join(',\n')+'\n        ]').join(',\n')+'\n    ]\n    static let names = palettes.keys.sorted()\n    static let labels: [String: String] = ['+Object.entries(labels).map(([name,label])=>JSON.stringify(name)+': '+JSON.stringify(label)).join(', ')+']\n    static func normalizedName(_ name: String?) -> String {\n        guard let name, palettes[name] != nil else { return "standard" }\n        return name\n    }\n}\n');
fs.copyFileSync('docs/licenses/github-readme-stats.txt', 'ios/App/App/Theme-LICENSE.txt');
console.log('Generated '+Object.keys(palettes).length+' palettes');
