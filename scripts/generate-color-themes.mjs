// Rebuild offline Web/native palettes from the MIT-licensed upstream snapshot.
import fs from 'node:fs';
const source = JSON.parse(fs.readFileSync('src/data/readme-themes.json', 'utf8'));
const rgb = value => {
 let hex = value.split(',').slice(value.includes(',') ? 1 : 0)[0];
 if(hex.length===3) hex=hex.split('').map(x=>x+x).join('');
 if(!/^[\da-f]{6}([\da-f]{2})?$/i.test(hex)) throw Error(value);
 const channels=[0,2,4].map(i=>parseInt(hex.slice(i,i+2),16));
 const alpha=hex.length===8 ? parseInt(hex.slice(6),16)/255 : 1;
 return channels.map(c=>Math.round(c*alpha+255*(1-alpha)));
};
const hex = c => '#'+c.map(v=>Math.round(v).toString(16).padStart(2,'0')).join('');
const mix=(a,b,t)=>a.map((v,i)=>v*(1-t)+b[i]*t);
const luminance=c=>c.map(x=>{const v=x/255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4;}).reduce((s,v,i)=>s+v*[.2126,.7152,.0722][i],0);
const contrast=(a,b)=>(Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05);
const readable=(color,bg)=>{
 const end=contrast([0,0,0],bg)>contrast([255,255,255],bg)?[0,0,0]:[255,255,255];
 for(let i=0;i<=100;i++){const c=mix(color,end,i/100);if(contrast(c,bg)>=4.6)return c;}
 return end;
};
const palettes={};
for(const [name,p] of Object.entries(source)) {
 const original=rgb(p.bg_color), originalScheme=luminance(original)<.179?'dark':'light';
 palettes[name]={};
 for(const scheme of ['light','dark']) {
  // Keep the source background in its original mode; tint its counterpart.
  const bg=scheme===originalScheme ? original : (scheme==='light'
   ? mix(original,[255,255,255],.94) : mix(original,[0,0,0],.91));
  const text=readable(rgb(p.text_color),bg), accent=readable(rgb(p.title_color),bg);
  const on=contrast([0,0,0],accent)>contrast([255,255,255],accent)?[0,0,0]:[255,255,255];
  palettes[name][scheme]={scheme,bg:hex(bg),surface:hex(bg),
   'surface-2':hex(mix(bg,text,.07)), 'input-surface':hex(bg), text:hex(text), muted:hex(readable(mix(bg,text,.8),bg)),
   border:hex(mix(bg,text,.28)),accent:hex(accent),'accent-hover':hex(mix(accent,on,.08)), 'on-accent':hex(on),selection:hex(mix(bg,text,.13)),
   warn:hex(readable(rgb('d29922'),bg))};
 }
}
const banner='Generated by scripts/generate-color-themes.mjs; source: github-readme-stats/themes/index.js (MIT). See docs/licenses/github-readme-stats.txt.';
fs.writeFileSync('src/js/color-themes.js','// '+banner+'\nexport const COLOR_THEMES = '+JSON.stringify(palettes,null,2)+';\n');
fs.writeFileSync('src/css/color-themes.css','/* '+banner+' */\n'+Object.entries(palettes).flatMap(([name,variants])=>Object.entries(variants).map(([scheme,p])=>'html[data-color-theme="'+name+'"][data-theme="'+scheme+'"] {\n'+Object.entries(p).map(([k,v])=>k==='scheme'?'  color-scheme: '+v+';':'  --'+k+': '+v+';').join('\n')+'\n}')).join('\n'));
fs.writeFileSync('ios/App/App/NativeColorThemes.swift','// '+banner+'\nimport Foundation\n\nenum AppColorThemes {\n    static let palettes: [String: [String: [String: String]]] = [\n'+Object.entries(palettes).map(([name,variants])=>'        '+JSON.stringify(name)+': [\n'+Object.entries(variants).map(([scheme,p])=>'            '+JSON.stringify(scheme)+': ['+Object.entries(p).map(([k,v])=>JSON.stringify(k)+': '+JSON.stringify(v)).join(', ')+']').join(',\n')+'\n        ]').join(',\n')+'\n    ]\n    static let names = palettes.keys.sorted()\n}\n');
console.log('Generated '+Object.keys(palettes).length+' palettes');
const license = fs.readFileSync('docs/licenses/github-readme-stats.txt', 'utf8');
const nativePath = 'ios/App/App/NativeColorThemes.swift';
fs.writeFileSync(nativePath, fs.readFileSync(nativePath, 'utf8').replace('\n}\n', '\n    static let license = """\n'+license.split('\n').map(line=>'    '+line).join('\n')+'\n    """\n}\n'));
fs.copyFileSync('docs/licenses/github-readme-stats.txt', 'src/data/readme-themes-LICENSE.txt');
