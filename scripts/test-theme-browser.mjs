import fs from 'node:fs';
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true });
try {
  const page = await browser.newPage({ colorScheme: 'light' });
  await page.route('https://theme.test/**', route => route.fulfill({ contentType: 'text/html', body: '<meta name="theme-color"><button id="toggle">Theme</button><div class="composer"><textarea placeholder="Write"></textarea><button type="submit">Post</button></div>' }));
  await page.goto('https://theme.test/');
  await page.addStyleTag({ content: fs.readFileSync('src/css/style.css', 'utf8') });
  await page.addStyleTag({ content: fs.readFileSync('src/css/color-themes.css', 'utf8') });
  await page.addScriptTag({ content: fs.readFileSync('src/js/color-themes.js', 'utf8').replace(/^export /gm, '') });
  await page.addScriptTag({ content: fs.readFileSync('src/js/theme.js', 'utf8').replace(/^import .*;\n/gm, '').replace(/^export \{.*\};\n/gm, '').replace(/^export /gm, '') });
  await page.evaluate(() => initThemeToggle(document.querySelector('#toggle')));
  assert.equal(await page.getAttribute('html', 'data-theme'), 'light');
  assert.equal(await page.evaluate(() => localStorage.getItem('spotcode-theme')), null);
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  const colors = await page.evaluate(() => {
    const button = getComputedStyle(document.querySelector('button[type=submit]'));
    const input = getComputedStyle(document.querySelector('textarea'));
    return { foreground: button.color, background: button.backgroundColor, input: input.color, scheme: getComputedStyle(document.documentElement).colorScheme };
  });
  assert.equal(colors.foreground, 'rgb(20, 20, 20)');
  assert.equal(colors.background, 'rgb(230, 230, 230)');
  assert.equal(colors.input, 'rgb(235, 235, 235)');
  assert.equal(colors.scheme, 'dark');
  await page.click('#toggle');
  assert.equal(await page.evaluate(() => localStorage.getItem('spotcode-theme')), 'light');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.emulateMedia({ colorScheme: 'dark' });
  assert.equal(await page.getAttribute('html', 'data-theme'), 'light');
  assert.equal(await page.getAttribute('meta[name=theme-color]', 'content'), '#fafafa');
  await page.evaluate(() => initThemeToggle(null));
  assert.equal(await page.getAttribute('html', 'data-theme'), 'light');
  const light = await page.locator('button[type=submit]').evaluate(button => ({ color: getComputedStyle(button).color, background: getComputedStyle(button).backgroundColor }));
  assert.equal(light.color, 'rgb(255, 255, 255)');
  assert.equal(light.background, 'rgb(31, 31, 31)');
  await page.evaluate(() => applyTheme('system'));
  assert.equal(await page.getAttribute('html', 'data-theme'), 'dark');
  assert.equal(await page.evaluate(() => localStorage.getItem('spotcode-theme')), null);
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  assert.equal(await page.evaluate(() => themePreference()), 'system');
  await page.evaluate(() => applyColorTheme('dracula'));
  assert.equal(await page.getAttribute('html', 'data-color-theme'), 'dracula');
  assert.equal(await page.getAttribute('html', 'data-theme'), 'light');
  const draculaLight = await page.evaluate(() => getComputedStyle(document.body).backgroundColor);
  await page.click('#toggle');
  assert.equal(await page.evaluate(() => colorThemePreference()), 'dracula');
  assert.equal(await page.getAttribute('html', 'data-theme'), 'dark');
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(40, 42, 54)');
  await page.evaluate(() => initThemeToggle(null));
  assert.equal(await page.evaluate(() => colorThemePreference()), 'dracula');
  assert.equal(await page.evaluate(() => themePreference()), 'dark');
  await page.evaluate(() => applyTheme('light'));
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), draculaLight);
  await page.evaluate(() => applyTheme('system'));
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  assert.equal(await page.evaluate(() => colorThemePreference()), 'dracula');
  await page.evaluate(() => applyColorTheme('nord'));
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(46, 52, 64)');
  await page.evaluate(() => applyColorTheme('missing'));
  assert.equal(await page.evaluate(() => colorThemePreference()), 'nord');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  assert.notEqual(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(46, 52, 64)');
  await page.evaluate(() => applyColorTheme('standard'));
  assert.equal(await page.getAttribute('html', 'data-theme'), 'light');
  console.log('PASS preset application, persistence, switching, reset, returning to system, system appearance, live switching, saved override, browser chrome, light/dark button and input colors');
} finally { await browser.close(); }
