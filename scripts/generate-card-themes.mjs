// Generate shared card presets from the vendored GitHub Readme Stats themes.
import fs from 'node:fs';
const upstream = JSON.parse(fs.readFileSync('src/data/readme-themes.json', 'utf8'));
const color = value => {
  const hex = value.length === 3 ? value.split('').map(c => c + c).join('') : value.slice(0, 6);
  if (!/^[0-9a-f]{6}$/i.test(hex)) throw new Error(`Invalid color: ${value}`);
  return '#' + hex.toLowerCase();
};
// Cards store opaque RGB colors and two background endpoints. Transparent
// themes use their RGB background; multi-stop gradients use the endpoints.
const palettes = Object.fromEntries(Object.entries(upstream).map(([name, p]) => {
  const stops = p.bg_color.includes(',') ? p.bg_color.split(',').slice(1) : [p.bg_color];
  return ['readme-' + name, [color(stops[0]), color(stops.at(-1)), color(p.text_color), color(p.title_color)]];
}));
const license = fs.readFileSync('docs/licenses/github-readme-stats.txt', 'utf8').trim();
const banner = '// Source: https://github.com/anuraghazra/github-readme-stats/blob/master/themes/index.js\n'
  + '// Generated by scripts/generate-card-themes.mjs\n' + license.split('\n').map(s => s ? '// ' + s : '//').join('\n');
function replaceBlock(path, body) {
  const source = fs.readFileSync(path, 'utf8');
  const block = '// BEGIN README CARD THEMES\n' + banner + '\n' + body + '\n// END README CARD THEMES';
  if (!source.includes('// BEGIN README CARD THEMES')) throw new Error('Missing marker: ' + path);
  fs.writeFileSync(path, source.replace(/\/\/ BEGIN README CARD THEMES[\s\S]*?\/\/ END README CARD THEMES/, block));
}
replaceBlock('src/js/business-cards.js', 'const readmeCardThemes = {\n' + Object.entries(palettes).map(([key, colors]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(colors)).join(',\n') + '\n};');
replaceBlock('ios/App/App/SupabaseService.swift', '    static let readmeCardThemes: [String: [String]] = [\n'
  + Object.entries(palettes).map(([key, colors]) => '        ' + JSON.stringify(key) + ': [' + colors.map(c => JSON.stringify(c)).join(', ') + ']').join(',\n') + '\n    ]');
console.log(`Generated ${Object.keys(palettes).length} business card themes`);
